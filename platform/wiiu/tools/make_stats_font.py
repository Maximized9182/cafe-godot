#!/usr/bin/env python3
"""Generates stats_font_data.c: JetBrains Mono (SIL OFL 1.1, see
tools/JetBrainsMono-OFL.txt) rasterised for the stats overlay at the two
pixel sizes it draws at (TV and GamePad), ASCII 32-126, one alpha byte per
pixel, cells top to bottom. Run from platform/wiiu with Pillow installed:
    python3 tools/make_stats_font.py JetBrainsMono-Regular.ttf stats_font_data.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = [15, 12]  # TV, GamePad (0.8x)
FIRST, LAST = 32, 126
font_path, out_path = sys.argv[1], sys.argv[2]

out = ["// Generated by tools/make_stats_font.py from JetBrains Mono (SIL Open Font License 1.1,",
       "// Copyright 2020 The JetBrains Mono Project Authors; see tools/JetBrainsMono-OFL.txt). Do not edit.",
       "// ASCII 32-126, one alpha byte per pixel, cells top to bottom.",
       "#include <stdint.h>", ""]
cw_l, ch_l, adv_l, asc_l = [], [], [], []
for i, size in enumerate(SIZES):
    font = ImageFont.truetype(font_path, size)
    asc, desc = font.getmetrics()
    adv = font.getlength("M")
    cw = int(adv + 0.999)
    ch = asc + desc
    cw_l.append(cw); ch_l.append(ch); adv_l.append(adv); asc_l.append(asc)
    out.append(f"const uint8_t wiiu_stats_font_{i}[95][{cw * ch}] = {{")
    for code in range(FIRST, LAST + 1):
        im = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(im).text((0, asc), chr(code), font=font, fill=255, anchor="ls")
        data = list(im.getdata())
        out.append(f"\t{{ // {code} {chr(code)!r}".replace("\\", "/"))
        for r in range(ch):
            out.append("\t\t" + ", ".join(f"0x{v:02x}" for v in data[r * cw:(r + 1) * cw]) + ",")
        out.append("\t},")
    out.append("};")
out.append("")
out.append(f"const uint32_t wiiu_stats_font_cell_w[{len(SIZES)}] = {{ {', '.join(map(str, cw_l))} }};")
out.append(f"const uint32_t wiiu_stats_font_cell_h[{len(SIZES)}] = {{ {', '.join(map(str, ch_l))} }};")
out.append(f"const float wiiu_stats_font_advance[{len(SIZES)}] = {{ {', '.join(f'{a:.3f}f' for a in adv_l)} }};")
open(out_path, "w").write("\n".join(out) + "\n")
print("cells", list(zip(cw_l, ch_l)), "advance", adv_l)
