#!/usr/bin/env python3
"""Generates crash_font_data.c: a 10x20 monospace bitmap font (ASCII 32-126)
for text drawn with GX2 alone (the crash overlay and the log), independent of
Godot's renderer and text server.

Rendered from DejaVu Sans Mono (Bitstream Vera / DejaVu license, free to
embed) with ImageMagick. Run on the VM from platform/wiiu:
    python3 tools/make_crash_font.py tools/DejaVuSansMono.ttf crash_font_data.c
"""
import subprocess
import sys

CELL_W, CELL_H = 10, 20
POINT_SIZE = 16
FIRST, LAST = 32, 126

font_path, out_path = sys.argv[1], sys.argv[2]


def render(ch):
    # -annotate treats % and \ as escapes and a leading @ as "read from file".
    text = ch.replace("\\", "\\\\").replace("%", "%%")
    if text.startswith("@"):
        text = "\\" + text
    cmd = [
        "magick", "-size", f"{CELL_W}x{CELL_H}", "xc:black",
        "-font", font_path, "-pointsize", str(POINT_SIZE),
        "-fill", "white", "-gravity", "center",
        "-annotate", "+0+0", text,
        "-depth", "8", "gray:-",
    ]
    data = subprocess.run(cmd, check=True, capture_output=True).stdout
    assert len(data) == CELL_W * CELL_H, (ch, len(data))
    return data


with open(out_path, "w", encoding="ascii") as out:
    out.write("// Generated by tools/make_crash_font.py from DejaVu Sans Mono (committed, so builds need no ImageMagick). Do not edit.\n")
    out.write("// 10x20 cells, ASCII 32-126, one alpha byte per pixel, rows top to bottom.\n")
    out.write("#include <stdint.h>\n\n")
    out.write(f"const uint32_t wiiu_crash_font_cell_w = {CELL_W};\n")
    out.write(f"const uint32_t wiiu_crash_font_cell_h = {CELL_H};\n")
    out.write(f"const uint32_t wiiu_crash_font_first = {FIRST};\n")
    out.write(f"const uint32_t wiiu_crash_font_count = {LAST - FIRST + 1};\n")
    out.write(f"const uint8_t wiiu_crash_font[{LAST - FIRST + 1}][{CELL_W * CELL_H}] = {{\n")
    for code in range(FIRST, LAST + 1):
        data = render(chr(code))
        out.write(f"\t{{ // {code} {chr(code)!r}\n")
        for row in range(CELL_H):
            line = data[row * CELL_W:(row + 1) * CELL_W]
            out.write("\t\t" + ", ".join(f"0x{b:02x}" for b in line) + ",\n")
        out.write("\t},\n")
    out.write("};\n")
print("wrote", out_path)
